//go:build ignore

package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

type CalendarEntry struct {
	Year     int      `json:"year"`
	Days     [12]int  `json:"days"`
	Source   string   `json:"source"`
	Verified bool     `json:"verified"`
}

func main() {
	dataFilePath := filepath.Join("data", "bs_calendar.json")
	dataBytes, err := os.ReadFile(dataFilePath)
	if err != nil {
		// Try looking one dir up if executed inside internal/gen
		dataFilePath = filepath.Join("..", "..", "data", "bs_calendar.json")
		dataBytes, err = os.ReadFile(dataFilePath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "failed to read calendar data: %v\n", err)
			os.Exit(1)
		}
	}

	var entries []CalendarEntry
	if err := json.Unmarshal(dataBytes, &entries); err != nil {
		fmt.Fprintf(os.Stderr, "failed to parse calendar json: %v\n", err)
		os.Exit(1)
	}

	if len(entries) != 131 {
		fmt.Fprintf(os.Stderr, "expected 131 entries (1970-2100), got %d\n", len(entries))
		os.Exit(1)
	}

	minYear := entries[0].Year
	maxYear := entries[len(entries)-1].Year

	// Find continuous MaxVerifiedYear
	maxVerifiedYear := minYear - 1
	for _, e := range entries {
		if e.Verified {
			if e.Year == maxVerifiedYear+1 {
				maxVerifiedYear = e.Year
			}
		} else {
			break
		}
	}

	// Compute cumulative days from anchor (1970-01-01 BS)
	cumulativeDays := make([]int32, len(entries)+1)
	var totalDays int32 = 0
	cumulativeDays[0] = 0

	for i, e := range entries {
		var yearSum int32 = 0
		for _, d := range e.Days {
			yearSum += int32(d)
		}
		totalDays += yearSum
		cumulativeDays[i+1] = totalDays
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/gen/gen_table.go; DO NOT EDIT.\n\n")
	buf.WriteString("package miti\n\n")
	buf.WriteString("// Calendar boundaries.\n")
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tMinYear         = %d\n", minYear)
	fmt.Fprintf(&buf, "\tMaxYear         = %d\n", maxYear)
	fmt.Fprintf(&buf, "\tMaxVerifiedYear = %d\n", maxVerifiedYear)
	fmt.Fprintf(&buf, ")\n\n")

	buf.WriteString("// Total supported days in the range (1970-01-01 to 2100-12-31 BS).\n")
	fmt.Fprintf(&buf, "const totalSupportedDays = %d\n\n", totalDays)

	buf.WriteString("// monthDays stores the number of days in each of the 12 months for BS years 1970-2100.\n")
	buf.WriteString("// Index is (year - MinYear). Memory: 131 * 12 = 1,572 bytes.\n")
	buf.WriteString("var monthDays = [131][12]uint8{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t/* %d */ {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d},\n",
			e.Year,
			e.Days[0], e.Days[1], e.Days[2], e.Days[3],
			e.Days[4], e.Days[5], e.Days[6], e.Days[7],
			e.Days[8], e.Days[9], e.Days[10], e.Days[11],
		)
	}
	buf.WriteString("}\n\n")

	buf.WriteString("// yearCumulativeDays stores the cumulative total days elapsed from 1970-01-01 BS up to the start of each year.\n")
	buf.WriteString("// yearCumulativeDays[0] is 0 (start of 1970). yearCumulativeDays[131] is total days in range.\n")
	buf.WriteString("// Memory: 132 * 4 = 528 bytes.\n")
	buf.WriteString("var yearCumulativeDays = [132]int32{\n")
	for i := 0; i < len(cumulativeDays); i += 6 {
		buf.WriteString("\t")
		for j := i; j < i+6 && j < len(cumulativeDays); j++ {
			fmt.Fprintf(&buf, "%d, ", cumulativeDays[j])
		}
		buf.WriteString("\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to format generated code: %v\n", err)
		os.Exit(1)
	}

	targetPath := "table.go"
	if err := os.WriteFile(targetPath, formatted, 0644); err != nil {
		targetPath = filepath.Join("..", "..", "table.go")
		if err := os.WriteFile(targetPath, formatted, 0644); err != nil {
			fmt.Fprintf(os.Stderr, "failed to write table.go: %v\n", err)
			os.Exit(1)
		}
	}

	fmt.Printf("Successfully generated %s (MinYear=%d, MaxYear=%d, MaxVerifiedYear=%d, TotalDays=%d)\n",
		targetPath, minYear, maxYear, maxVerifiedYear, totalDays)
}

